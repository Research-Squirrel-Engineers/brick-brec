"""Wikidata mapping for the candidates of the identification figure (and the other terms with a search term).

NOT part of `python main.py`: it needs the network. Run it on your own machine (Windows cmd, one line):

    python py/wikidata/match.py            lists the hits per term, you pick a number (Enter = skip, s = search again with your own term)
    python py/wikidata/match.py --set ex:c_cobi=Q123   enter a QID you know (any node, also without a search term); label and description are fetched
    python py/wikidata/match.py --list     only writes dist/wikidata_candidates.md (all hits, no questions) so the hits can be checked together

The picks go to data/wikidata_mapping.ttl (skos:closeMatch plus the Wikidata label as rdfs:label). That file is a curated source:
`python main.py` reads it (check, figures, pages). Nothing is taken over automatically; picking is a judgement.
"""
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import rdflib

ROOT = Path(__file__).resolve().parents[2]
ONT, OUT, CAND = ROOT / "ontology" / "brec.ttl", ROOT / "data" / "wikidata_mapping.ttl", ROOT / "dist" / "wikidata_candidates.md"
L = rdflib.Namespace("https://w3id.org/brec/ontology#")
EX = "https://w3id.org/brec/id/"
HEAD = ("# Curated Wikidata mappings (written by py/wikidata/match.py, checked by hand). Each line: node, skos:closeMatch, label | description from Wikidata.\n"
        "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .\n@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n"
        "@prefix wd: <http://www.wikidata.org/entity/> .\n@prefix ex: <https://w3id.org/brec/id/> .\n\n")
LINE = re.compile(r'^(ex:\S+) skos:closeMatch (wd:Q\d+) \.\s*# (.*)$')


def search(term, n=8):
    url = "https://www.wikidata.org/w/api.php?" + urllib.parse.urlencode(
        {"action": "wbsearchentities", "search": term, "language": "en", "uselang": "en", "format": "json", "limit": n})
    req = urllib.request.Request(url, headers={"User-Agent": "brick-brec-match/1.0 (research use; github.com/Research-Squirrel-Engineers/brick-brec)"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)["search"]


def read_current():
    cur = {}
    if OUT.exists():
        for ln in OUT.read_text(encoding="utf-8").splitlines():
            m = LINE.match(ln)
            if m:
                cur[m.group(1)] = (m.group(2), m.group(3))
    return cur


def write_current(cur):
    lines = []
    for k, (q, c) in sorted(cur.items()):
        label = c.split(" | ")[0].replace("\\", "").replace('"', "'")
        lines += [f"{k} skos:closeMatch {q} .  # {c}", f'{q} rdfs:label "{label}"@en .']
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEAD + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def terms():
    g = rdflib.Graph()
    g.parse(ONT, format="turtle")
    t = {"ex:" + str(s).replace(EX, ""): str(o) for s, o in g.subject_objects(L.wikidataSearchTerm)}
    return dict(sorted(t.items()))


def set_qids(pairs):
    cur = read_current()
    for pair in pairs:
        key, qid = pair.split("=")
        qid = qid.strip().upper().replace("WD:", "")
        if not re.fullmatch(r"Q\d+", qid):
            sys.exit(f"{pair}: not a QID")
        url = "https://www.wikidata.org/w/api.php?" + urllib.parse.urlencode(
            {"action": "wbgetentities", "ids": qid, "props": "labels|descriptions", "languages": "en", "format": "json"})
        req = urllib.request.Request(url, headers={"User-Agent": "brick-brec-match/1.0 (research use; github.com/Research-Squirrel-Engineers/brick-brec)"})
        with urllib.request.urlopen(req, timeout=30) as r:
            e = json.load(r)["entities"][qid]
        label = e.get("labels", {}).get("en", {}).get("value", qid)
        desc = e.get("descriptions", {}).get("en", {}).get("value", "")
        cur[key.strip()] = ("wd:" + qid, f"{label} | {desc}")
        print(f"{key.strip()} -> {qid}  {label}: {desc}")
    write_current(cur)
    print(f"written: {OUT.relative_to(ROOT)} ({len(cur)} mappings); now run: python main.py --strict")


def main():
    if "--set" in sys.argv:
        return set_qids([a for a in sys.argv[sys.argv.index("--set") + 1:] if "=" in a])
    only_list = "--list" in sys.argv
    cur = read_current()
    md = ["# Wikidata candidates (generated by py/wikidata/match.py; not a source)\n"]
    for key, term in terms().items():
        while True:
            try:
                hits = search(term)
            except Exception as e:   # network, proxy, timeout
                print(f"{key}: search for '{term}' failed: {e}")
                hits = []
            md.append(f"\n## {key}  (search: {term})\n")
            md += [f"- `{h['id']}` {h.get('label')}: {h.get('description', '')}" for h in hits] or ["- no hits"]
            if only_list:
                break
            print(f"\n{key}  (search: {term})" + (f"   current: {cur[key][0]}" if key in cur else ""))
            for i, h in enumerate(hits):
                print(f"  [{i}] {h['id']}  {h.get('label')} - {h.get('description', '')}")
            sel = input("  number, Enter = skip, s = search again: ").strip()
            if sel.lower() == "s":
                term = input("  new search term: ").strip() or term
                continue
            if sel.isdigit() and int(sel) < len(hits):
                h = hits[int(sel)]
                cur[key] = ("wd:" + h["id"], f"{h.get('label')} | {h.get('description', '')}".replace("\n", " "))
            break
    CAND.parent.mkdir(parents=True, exist_ok=True)
    CAND.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"\nwritten: {CAND.relative_to(ROOT)}")
    if not only_list:
        write_current(cur)
        print(f"written: {OUT.relative_to(ROOT)} ({len(cur)} mappings); now run: python main.py --strict")


if __name__ == "__main__":
    main()
